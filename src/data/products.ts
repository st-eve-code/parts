import { brandMap } from "./brands";
import { productImages } from "./images";
import type { BrandId, CategoryId, Product, StockStatus } from "./types";

function slugify(value: string): string {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)+/g, "");
}

function hash(value: string): number {
  let h = 5381;
  for (let i = 0; i < value.length; i++) {
    h = (h * 33) ^ value.charCodeAt(i);
  }
  return Math.abs(h);
}

const USD_PER_INR = 1 / 83;

function toUSD(inr: number): number {
  return Math.round(inr * USD_PER_INR * 100) / 100;
}

interface PartOpts {
  brand: BrandId;
  category: CategoryId;
  name: string;
  price: number;
  mrp?: number;
  models: string[];
  years?: string;
  spec?: string;
  description?: string;
  rating?: number;
  ratingCount?: number;
  badge?: string;
  oem?: string;
  stock?: StockStatus;
  featured?: boolean;
}

function part(opts: PartOpts): Product {
  const brand = brandMap[opts.brand];
  const slug = slugify(`${opts.brand} ${opts.category} ${opts.name}`);
  const variant = hash(slug) % 3;
  const specification: string[] = [];
  if (opts.models.length > 0) {
    specification.push(`Applicability Base Model – ${opts.models.join(" | ")}`);
  }
  if (opts.years) {
    specification.push(`Applicable Model Years – ${opts.years}`);
  }
  if (opts.spec) {
    specification.push(`Specification – ${opts.spec}`);
  }
  specification.push(`Brand – ${brand.name}`);
  if (opts.oem) {
    specification.push(`OEM Part No – ${opts.oem}`);
  }
  return {
    slug,
    name: opts.name,
    brand: opts.brand,
    category: opts.category,
    image: productImages[slug] ?? `/images/parts/${opts.category}-${variant}.svg`,
    price: toUSD(opts.price),
    mrp: opts.mrp === undefined ? undefined : toUSD(opts.mrp),
    rating: opts.rating,
    ratingCount: opts.ratingCount,
    stock: opts.stock ?? "in-stock",
    badge: opts.badge,
    oem: opts.oem,
    specification,
    description:
      opts.description ??
      `${opts.name} is a 100% genuine, OEM-grade spare part for ${brand.name} two-wheelers. Delivered in original factory packaging with assured prices and genuine quality guaranteed.`,
    applicability: opts.models.map((model) => ({
      make: brand.name,
      model,
      year: opts.years ?? "2015 – 2025",
    })),
    featured: opts.featured,
  };
}

